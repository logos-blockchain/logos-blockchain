use std::sync::LazyLock;

use lb_groth16::{COMPRESSED_PROOF_SIZE, CompressedGroth16Proof};
use lb_key_management_system_keys::keys::{Ed25519Signature, ZkSignature};

use crate::{
    mantle::ops::ZkAndEd25519Proof,
    proofs::{
        channel_multi_sig_proof::{ChannelMultiSigProof, IndexedSignature, IndexedSignatures},
        leader_claim_proof::Groth16LeaderClaimProof,
    },
};

pub static ZK_SIG: LazyLock<ZkSignature> =
    LazyLock::new(|| ZkSignature::new(CompressedGroth16Proof::from_bytes(&[1u8; 128])));

pub static ED25519_SIG: LazyLock<Ed25519Signature> =
    LazyLock::new(|| Ed25519Signature::from_bytes(&[1u8; 64]));

pub static ZK_AND_ED25519_SIGS: LazyLock<ZkAndEd25519Proof> =
    LazyLock::new(|| ZkAndEd25519Proof::new(ZK_SIG.clone(), *ED25519_SIG));

pub static POC: LazyLock<Groth16LeaderClaimProof> = LazyLock::new(|| {
    Groth16LeaderClaimProof::new(CompressedGroth16Proof::from_bytes(
        &[1u8; COMPRESSED_PROOF_SIZE],
    ))
});

pub static CHANNEL_MULTI_SIG: LazyLock<ChannelMultiSigProof> = LazyLock::new(|| {
    ChannelMultiSigProof::new(IndexedSignatures::new_unchecked(vec![
        IndexedSignature::new(0, Ed25519Signature::from_bytes(&[1u8; 64])),
        IndexedSignature::new(7, Ed25519Signature::from_bytes(&[2u8; 64])),
    ]))
});

